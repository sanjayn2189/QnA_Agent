"""
Answer Quality Evaluation for the ConfluenceAssist RAG pipeline.

Evaluates the generated answer end-to-end by running each query through the
full CRAG graph and judging the output against the retrieved context.

Five criteria (LLM-as-judge):
  - Faithfulness    (0-1): Is the answer grounded in context? (no hallucinations)
  - Correctness     (0-1): Does it correctly address the query?
  - Completeness    (0-1): Does it cover everything the query asks?
  - Conciseness     (0-1): Is it clear and to the point?
  - Hallucination   (0|1): Binary — any fabricated/unsupported claim?
  - Overall Score   (0-1): LLM's holistic judgment

Eval Stack:
  Recall@K + MRR   → Did we retrieve the right document?
  Context Quality  → Was the retrieved context useful?
  Answer Quality   → Was the final answer good?   ← THIS SCRIPT

Usage:
    python eval/answer_quality.py              # default
    python eval/answer_quality.py --top-n 5   # show 5 worst answers
"""

import json
import argparse
import sys
import os
import re

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from langchain_core.messages import HumanMessage
from langchain_groq import ChatGroq

from src.agent.graph import get_graph
from config.settings import settings


ANSWER_QUALITY_PROMPT = """\
You are evaluating the quality of an answer generated by a retrieval-augmented system.

Your job is to assess whether the answer is correct, grounded in the provided context, and complete.

Query:
{query}

Retrieved Context:
{context}

Generated Answer:
{answer}

Evaluate the answer on the following criteria:

1. Faithfulness (0 to 1):
   Is the answer fully supported by the retrieved context?
   - 1 = completely grounded in context
   - 0 = contains hallucinations or unsupported claims

2. Answer Correctness (0 to 1):
   Does the answer correctly address the query based on the context?

3. Completeness (0 to 1):
   Does the answer fully cover what the query is asking, or is something important missing?

4. Conciseness (0 to 1):
   Is the answer clear and to the point without unnecessary verbosity?

5. Hallucination (0 or 1):
   - 1 = hallucination present (any unsupported or fabricated info)
   - 0 = no hallucination

Instructions:
- Be strict in scoring
- Do not assume facts not present in the context
- If the answer includes information not in the context, penalize faithfulness and mark hallucination = 1
- Prefer lower scores over overly generous scoring

Return ONLY valid JSON in this format:
{{
  "faithfulness": <float>,
  "correctness": <float>,
  "completeness": <float>,
  "conciseness": <float>,
  "hallucination": <0 or 1>,
  "overall_score": <float>,
  "explanation": "<brief explanation>"
}}"""


def load_eval_dataset(path: str = "eval/eval_dataset.json") -> list[dict]:
    with open(path, "r") as f:
        return json.load(f)


def build_context_block(docs: list) -> str:
    """Combine docs into a numbered context block for the judge."""
    parts = []
    for i, doc in enumerate(docs, 1):
        title = doc.metadata.get("title", "Unknown")
        parts.append(f"[Chunk {i} — {title}]\n{doc.page_content.strip()}")
    return "\n\n---\n\n".join(parts)


def strip_confidence_tag(answer: str) -> str:
    """Remove the [CONFIDENCE: XX%] tag the pipeline appends."""
    return re.sub(r"\[CONFIDENCE:\s*\d+%?\]", "", answer).strip()


def evaluate_answer_quality(
    query: str,
    context: str,
    answer: str,
    llm: ChatGroq,
) -> dict:
    """
    Use LLM-as-judge to evaluate a generated answer against its retrieved context.

    Returns scores for faithfulness, correctness, completeness, conciseness,
    hallucination, overall_score, and explanation.
    """
    prompt = ANSWER_QUALITY_PROMPT.format(
        query=query,
        context=context,
        answer=answer,
    )

    try:
        response = llm.invoke([HumanMessage(content=prompt)])
        raw = response.content.strip()

        # Strip markdown code fences if present
        if raw.startswith("```"):
            raw = raw.split("```")[1]
            if raw.startswith("json"):
                raw = raw[4:]
            raw = raw.strip()

        result = json.loads(raw)
        return {
            "faithfulness":  float(result.get("faithfulness", 0.0)),
            "correctness":   float(result.get("correctness", 0.0)),
            "completeness":  float(result.get("completeness", 0.0)),
            "conciseness":   float(result.get("conciseness", 0.0)),
            "hallucination": int(result.get("hallucination", 0)),
            "overall_score": float(result.get("overall_score", 0.0)),
            "explanation":   result.get("explanation", ""),
        }

    except Exception as e:
        print(f"    ⚠️  Failed to parse LLM response: {e}")
        return {
            "faithfulness":  None,
            "correctness":   None,
            "completeness":  None,
            "conciseness":   None,
            "hallucination": None,
            "overall_score": None,
            "explanation":   f"Parse error: {e}",
        }


def run_answer_quality_eval(
    dataset_path: str = "eval/eval_dataset.json",
    top_n_worst: int = 3,
):
    """
    Run full answer quality evaluation across the dataset.

    For each query:
    1. Run through the full CRAG graph → get answer + retrieved_docs
    2. Judge the answer with LLM-as-judge
    3. Report per-query scores and aggregates
    """
    dataset = load_eval_dataset(dataset_path)
    total = len(dataset)

    graph = get_graph()
    llm = ChatGroq(
        model=settings.llm_model,
        temperature=0.0,
        api_key=settings.groq_api_key,
    )

    results = []
    hallucination_count = 0

    print(f"\n{'='*70}")
    print(f"  Answer Quality Evaluation — {total} queries")
    print(f"  (running full CRAG pipeline per query)")
    print(f"{'='*70}\n")

    for i, item in enumerate(dataset, 1):
        query = item["query"]
        print(f"  [{i:2d}/{total}] {query}")

        # ── Step 1: Run through full CRAG graph ───────────────────────────
        try:
            state = graph.invoke({
                "query": query,
                "chat_history": [],
                "retry_count": 0,
                "metadata": {},
            })
        except Exception as e:
            print(f"          ⚠️  Graph error: {e}\n")
            results.append({"query": query, "error": str(e)})
            continue

        raw_answer = state.get("answer", "")
        answer = strip_confidence_tag(raw_answer)

        # Use relevant_docs if grader kept any, else fall back to retrieved_docs
        docs = state.get("relevant_docs") or state.get("retrieved_docs", [])
        context = build_context_block(docs)

        if not answer:
            print(f"          ⚠️  Empty answer returned\n")
            results.append({"query": query, "error": "empty answer"})
            continue

        # ── Step 2: Judge the answer ───────────────────────────────────────
        scores = evaluate_answer_quality(query, context, answer, llm)

        # Display
        if scores["faithfulness"] is not None:
            f   = scores["faithfulness"]
            c   = scores["correctness"]
            cmp = scores["completeness"]
            con = scores["conciseness"]
            hal = scores["hallucination"]
            ov  = scores["overall_score"]

            if hal == 1:
                hallucination_count += 1

            label = "🟢" if ov >= 0.75 else ("🟡" if ov >= 0.5 else "🔴")
            hal_flag = "🚨 HALLUCINATION" if hal == 1 else "✅ No hallucination"

            print(f"          {label} Overall={ov:.2f}  Faith={f:.2f}  "
                  f"Correct={c:.2f}  Complete={cmp:.2f}  Concise={con:.2f}")
            print(f"          {hal_flag}")
            print(f"          💬 {scores['explanation']}")
        else:
            print(f"          ⚠️  Scoring failed")
        print()

        results.append({
            "query":            query,
            "expected_source":  item.get("expected_source", ""),
            "answer_snippet":   answer[:200] + "..." if len(answer) > 200 else answer,
            **scores,
        })

    # ── Aggregates ────────────────────────────────────────────────────────
    valid = [r for r in results if r.get("faithfulness") is not None]

    def avg(key):
        return sum(r[key] for r in valid) / len(valid) if valid else 0.0

    print(f"{'='*70}")
    print(f"  AGGREGATE RESULTS")
    print(f"{'='*70}")
    print(f"  Avg Faithfulness:  {avg('faithfulness'):.4f}  (higher = less hallucination)")
    print(f"  Avg Correctness:   {avg('correctness'):.4f}")
    print(f"  Avg Completeness:  {avg('completeness'):.4f}")
    print(f"  Avg Conciseness:   {avg('conciseness'):.4f}")
    print(f"  Avg Overall Score: {avg('overall_score'):.4f}")
    print(f"  Hallucinations:    {hallucination_count}/{len(valid)} queries flagged")
    print(f"  Evaluated:         {len(valid)}/{total} queries")
    print(f"{'='*70}\n")

    # Worst queries by overall score
    if valid and top_n_worst > 0:
        worst = sorted(valid, key=lambda r: r["overall_score"])[:top_n_worst]
        print(f"  ⚠️  Bottom {top_n_worst} queries by overall score:")
        for r in worst:
            hal_tag = " 🚨" if r.get("hallucination") == 1 else ""
            print(f"    • [overall={r['overall_score']:.2f}{hal_tag}] {r['query']}")
            print(f"      → {r['explanation']}")
        print()

    # Save output
    output = {
        "total": total,
        "evaluated": len(valid),
        "hallucinations_found": hallucination_count,
        "avg_faithfulness":  round(avg("faithfulness"), 4),
        "avg_correctness":   round(avg("correctness"), 4),
        "avg_completeness":  round(avg("completeness"), 4),
        "avg_conciseness":   round(avg("conciseness"), 4),
        "avg_overall_score": round(avg("overall_score"), 4),
        "details": results,
    }
    output_path = "eval/answer_quality_results.json"
    with open(output_path, "w") as f:
        json.dump(output, f, indent=2)
    print(f"  📄 Results saved to: {output_path}\n")

    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="End-to-end answer quality evaluation for the RAG pipeline"
    )
    parser.add_argument(
        "--dataset", type=str, default="eval/eval_dataset.json",
        help="Path to evaluation dataset JSON"
    )
    parser.add_argument(
        "--top-n", type=int, default=3,
        help="Number of worst-scoring answers to highlight (default: 3)"
    )
    args = parser.parse_args()

    run_answer_quality_eval(dataset_path=args.dataset, top_n_worst=args.top_n)
